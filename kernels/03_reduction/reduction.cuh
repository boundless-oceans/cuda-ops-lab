// kernels/03_reduction/reduction.cuh
//
// 第 3 章 reduction 的 host launcher 声明。
//
// 铁律不变：这个头文件以及所有 .cu 里**不出现任何 torch 符号**。
//
// =========================== 本章的问题与它和第 2 章的区别 ===========================
//
//     x: float32[N]  →  out: float32[1]
//
// 第 2 章的输出和输入一样大，搬运量是 2N 或 3N 字节，瓶颈只有"带宽打满"一件事。
// 归约则完全不同，出现了第 2 章完全没有的两类问题：
//
//   1. **输出比输入小 4N 倍**，搬运量 ≈ 4N + 4 字节 —— 几乎是纯读。于是"带宽"
//      这个词本身要小心：只有读的那一份算数，写的 4 个字节可以忽略，
//      但它带来的 4N 分之一的算术强度下降是真实的（见本章 README 第 2 段）。
//
//   2. **元素之间产生了依赖**：N 个值必须合并成 1 个，于是绕不开
//      线程内串行累加 → 块内树 → block 之间汇总这三层结构。
//      第 2 章每个元素独立，永远不需要 __syncthreads()；这里必须有。
//
// 本章要回答三个问题：
//
//   Q1  一个"结构正确但不做任何微调"的归约，离带宽上限有多远？            → v1
//   Q2  教科书里那套块内优化（消 bank conflict、warp shuffle）还换得来东西吗？ → v2 / v3
//   Q3  如果 block 数用错了，前面所有块内优化值多少钱？                     → v4
//
// =============================== 先算理论下限（写代码之前） ===============================
//
// N = 2^24 = 16,777,216（与第 2 章的基准形状一致，便于横向比较）
//
//     搬运 B = 读 4N + 写 4 = 67,108,868 字节 = 67.1 MB
//     运算 F = N - 1 ≈ 1.68e7 FLOP
//     算术强度 I = F / B = 0.25 FLOP/Byte   （第 2 章的 add 是 0.083）
//
// 本机 machine balance ≈ 54 FLOP/Byte（见 scripts/check_env.py 的 [5/7] 一节），
// 差了 200 多倍 → 仍然是 memory-bound，目标还是打满带宽。
//
//     理论最短耗时 = 67.1 MB ÷ 256.0 GB/s = **262.1 µs**
//
// ================================= 一个必须先说清楚的预测 =================================
//
// 网上流传的经典归约阶梯（2007 年那份 "Optimizing Parallel Reduction in CUDA"）
// 是 5 级爬升：交错寻址 → 非发散 → 顺序寻址 → 展开 → 多元素/线程，最后能快 5 倍以上。
//
// **在这台机器上，那个阶梯不应该重现。** 原因是算一笔账：
//
//     块内树一共 8 级，每级 = 1 次 __syncthreads + 1 次 smem 读写
//     粗估每级 ~50 cycle，8 级 ≈ 400 cycle
//     sm_89 约 1.6e9 cycle/s  →  400 cycle ≈ **0.25 µs**
//
// 而理论下限是 262.1 µs。也就是说**整个块内归约只占 0.1% 的耗时** ——
// 把 8 级压成 1 级、把同步全删掉，最多也就能省下这 0.1%。
//
// 所以在 2007 年那些卡上（块内归约占比高、且当时全局访存远没打满）能测出 5 倍，
// 在这台机上预期是"**一条平线**"。v2 / v3 照样要写、要测，因为
// **"测不出差别"本身就是要记录的结论** —— 它能让你以后不再花时间优化这 0.1%。
//
// 真正能拉开差距的是 v4：只用一个 block，等于把 24 个 SM 里的 23 个关掉。
#pragma once

#include <cuda_runtime.h>

#include <cstdint>

#include "kernels/03_reduction/reduction_config.cuh"
#include "kernels/common/cuda_check.h"
#include "kernels/common/device.h"

namespace ops_lab {
namespace reduction {

// ---------------------------------------------------------------------------
// 所有变体共用的准备步骤：把输出写成单位元
//
// 为什么必须有这一步：多 block 的最终合并靠原子操作（atomicAdd / CAS 版
// atomicMax），而原子操作是"读-改-写" —— **没有正确的初值就没有正确的结果**。
// cudaMemsetAsync 只能按字节填，写不出 -inf，所以统一用一个小 kernel。
//
// 顺带解决另一个问题：n == 0 时主 kernel 不启动，但输出仍然必须被写出来
// （空数组的和是 0、最大值是 -inf）。把这一步放进 launcher，绑定层就不需要
// 为空输入写特例，"空输入"这条路径也就不会被漏掉。
// ---------------------------------------------------------------------------
void init_reduction_output(float* out, float identity, cudaStream_t stream);

// ---------------------------------------------------------------------------
// v0~v3 共用的 grid 计算：**够用就好**，不随 n 增长
//
//     grid = min(覆盖 n 所需的 block 数, SM 数 × 每 SM 能驻留的 block 数)
//
// 为什么截断，而不是"一线程一元素"：每个 block 结束时要对 out 做一次原子操作。
// 2^24 个元素按 256 一线程分需要 65536 个 block，也就是 65536 次打在**同一个
// 地址**上的原子操作 —— 它们会被 L2 串行化，代价可能比整个 kernel 还大。
// 截断到 144 个 block（本机 24 SM × 6）之后只剩 144 次，可以忽略；
// 剩下的元素靠 grid-stride 循环覆盖。
//
// 注意这是一个**有意的取舍**，不是"最优解"：它换来了便宜的汇总，
// 代价是每个线程要走 400 多轮循环（也就是 ILP 必须靠硬件把多个 load 排起来）。
// 第 5 段的 ncu 观察就是去确认这件事。
// ---------------------------------------------------------------------------
inline unsigned int grid_for_reduction(int64_t n) {
  const int64_t cap = default_grid_size(kBlockSize);
  const int64_t needed = ceil_div(n, kBlockSize);
  const int64_t g = needed < cap ? needed : cap;
  return static_cast<unsigned int>(g < 1 ? 1 : g);
}

// ---------------------------------------------------------------------------
// v1_naive —— 结构正确、不做任何微调，本章的**基准点**也是**答案**
//
// 思路
//   ① 读：grid-stride 循环，相邻线程读相邻地址（合并访存）
//   ② 合并：块内 smem 顺序寻址树（这就是"没有 bank conflict"的那种写法）
//   ③ 汇总：每个 block 对自己那份结果做一次原子操作
//
// 限制（故意保留）
//   block 内用最简单的树，没有做任何"优化"。这正是要测的东西：
//   在这台机器上这些"优化"值不值钱。
//
// 预期
//   **~90% 峰值带宽（约 290 µs）**。理由：读是合并的、每个线程有 400 多次
//   独立累加可以掩盖访存延迟、汇总只花 144 次原子操作。
//   块内那棵树的 0.25 µs 相对 262 µs 可以忽略，所以这一级就已经接近上限。
// ---------------------------------------------------------------------------
void sum_v1_naive(const float* x, float* out, int64_t n, cudaStream_t stream);
void max_v1_naive(const float* x, float* out, int64_t n, cudaStream_t stream);

// ---------------------------------------------------------------------------
// v0_uncoalesced —— 反面教材
//
// 思路
//   索引写成 i = threadIdx.x * gridDim.x + blockIdx.x，相邻线程的地址因此相隔
//   gridDim.x 个元素。一个 warp 的 32 个线程落在 32 条不同的 cache line 上，
//   一次访存请求被拆成 32 个事务。
//
// 与 v1_naive 的关系
//   **只差索引公式那一行**，其余（grid、块内树、原子合并）完全相同，
//   所以阶梯表里 v0 → v1 的差距只能归因于访存模式。
//
// 预期
//   有效带宽 ≈ 峰值的 20%。注意第 2 章的教训：这一级大概只会慢 4~5 倍，
//   而不是教科书说的 32 倍 —— 因为固定 tid、连续 bid 访问的是连续地址，
//   L2 会把复用接住。**这里能不能重现那个 4~5 倍，是本章第一个可证伪的预测。**
// ---------------------------------------------------------------------------
void sum_v0_uncoalesced(const float* x, float* out, int64_t n, cudaStream_t stream);
void max_v0_uncoalesced(const float* x, float* out, int64_t n, cudaStream_t stream);

// ---------------------------------------------------------------------------
// v2_smem_tree —— 给共享内存加 padding，消 bank conflict
//
// 思路
//   按 warp 切开共享内存，每个 warp 的 32 个值后面补 1 个空位，
//   warp w 的 lane l 落在 smem[w*33 + l]。经典"padding 消 bank conflict"。
//
// 与 v1_naive 的关系
//   **只差 smem 的下标计算**（`tid` → `tid + tid/32`）。
//
// 预期
//   **≈ v1（差别应在测量噪声内）**，理由是 v1 用的顺序寻址本来就没有 bank
//   conflict 可消（推导见 reduction_block.cuh）。这一级存在的意义是
//   **验证这条经典建议的适用条件**，而不是指望它变快。
//
//   如果实测 v2 明显慢于 v1，那说明多出来的地址计算不是免费的，
//   也是一个要如实记录的结论。
// ---------------------------------------------------------------------------
void sum_v2_smem_tree(const float* x, float* out, int64_t n, cudaStream_t stream);
void max_v2_smem_tree(const float* x, float* out, int64_t n, cudaStream_t stream);

// ---------------------------------------------------------------------------
// v3_warp_shuffle —— 块内改用 warp shuffle
//
// 思路
//   前 5 级（256 → 8）在 warp 内用 __shfl_down_sync 完成，不需要同步；
//   8 个 warp 的部分和落到 smem、同步 1 次；第二级（8 → 1）再用 3 次 shuffle。
//   共享内存访问从 8×256 次降到 8 次，__syncthreads 从 8 次降到 1 次。
//
// 与 v1_naive 的关系
//   只差块内合并这一步调用的函数（见 reduction_block.cuh），读和汇总是同一份。
//
// 预期
//   **≈ v1**。按上面的账，8 级同步加起来约 0.25 µs，删掉 7 次同步最多省
//   0.2 µs，而 kernel 本身是 262 µs 量级 —— **省下 0.1%，测不出来**。
//   如果真测出了差别，那多半是噪声或者 clock 漂移，不是 shuffle 的功劳。
//
//   这一级在别的地方有真实价值：同步次数少意味着 block 之间的等待少，
//   在小 batch / 低占用率场景下更容易掩盖延迟。但那不是本章的测法。
// ---------------------------------------------------------------------------
void sum_v3_warp_shuffle(const float* x, float* out, int64_t n, cudaStream_t stream);
void max_v3_warp_shuffle(const float* x, float* out, int64_t n, cudaStream_t stream);

// ---------------------------------------------------------------------------
// v4_single_block —— 故意回退：只用一个 block
//
// 思路
//   块内沿用 v3 的 warp shuffle（本章最"快"的那套块内写法），
//   但 **grid = 1**：整个 2^24 的数组交给一个 block 的 256 个线程去读。
//
// 与 v3 的关系
//   **只差启动时的 grid**。这个变体存在的意义就是把这一个变量单独拎出来量化：
//   前面 v1→v2→v3 折腾了半天块内写法，而这里只是少写了一个 grid 参数，
//   代价有多大。
//
// 预期
//   **5~10% 峰值**（约 2.6~5.2 ms），也就是比 v1 慢 10~18 倍。
//   机器上跑着的线程从 36864 个降到 256 个，只有 1/24 的 SM 在工作，
//   而且每个线程的循环依赖链很长，很难把访存延迟藏住。
//
//   至于为什么把**回退**放在阶梯最后一级而不是第一级：因为这一级要对比的对象
//   是已经调到位的 v3，不是从零开始的 v0。放在最后，表上读到的就是
//   "块内优化全部做完之后，用错 block 数照样掉一个数量级"。
// ---------------------------------------------------------------------------
void sum_v4_single_block(const float* x, float* out, int64_t n, cudaStream_t stream);
void max_v4_single_block(const float* x, float* out, int64_t n, cudaStream_t stream);

}  // namespace reduction
}  // namespace ops_lab
